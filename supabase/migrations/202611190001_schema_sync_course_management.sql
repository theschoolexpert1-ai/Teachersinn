-- Keep the legacy boolean compatible while status is the lifecycle source of
-- truth. This prevents direct PostgREST writes from creating contradictory
-- states during the repository migration.
create or replace function public.sync_course_publication_state()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.published = (new.status = 'published');
  return new;
end;
$$;
create trigger courses_publication_state before insert or update of status on public.courses
for each row execute function public.sync_course_publication_state();

-- Curriculum is immutable after the first enrollment. Administrators can
-- archive the course without deleting progress, CPD history, or certificates.
create or replace function public.protect_enrolled_course_curriculum()
returns trigger language plpgsql set search_path = '' as $$
declare
  affected_course bigint;
begin
  affected_course = case when tg_op = 'INSERT' then new.course_id else old.course_id end;
  if exists (select 1 from public.enrollments e where e.course_id = affected_course) then
    raise exception 'curriculum cannot change after enrollment' using errcode = '23514';
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
create trigger lessons_protect_enrolled_curriculum
before insert or update or delete on public.lessons
for each row execute function public.protect_enrolled_course_curriculum();

-- New owner-scoped domains.
alter table public.career_profiles enable row level security;
alter table public.job_applications enable row level security;
alter table public.notification_preferences enable row level security;

create policy career_profiles_own on public.career_profiles for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create policy job_applications_read on public.job_applications for select to authenticated
  using (user_id = (select auth.uid()) or public.is_admin());
create policy job_applications_insert_own on public.job_applications for insert to authenticated
  with check (
    user_id = (select auth.uid()) and status = 'applied'
    and exists (select 1 from public.jobs j where j.id = job_id and j.status = 'open')
  );

create policy notification_preferences_own on public.notification_preferences for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- Replace only the affected read policies. Existing write policies remain
-- administrator-only and continue to use authoritative account settings.
drop policy courses_read on public.courses;
create policy courses_read on public.courses for select to authenticated using (
  status = 'published' or public.is_admin()
  or exists (
    select 1 from public.enrollments e
    where e.course_id = courses.id and e.user_id = (select auth.uid())
  )
);

drop policy lessons_read on public.lessons;
create policy lessons_read on public.lessons for select to authenticated using (
  public.is_admin()
  or exists (
    select 1 from public.enrollments e
    where e.course_id = lessons.course_id and e.user_id = (select auth.uid())
  )
  or exists (
    select 1 from public.courses c
    where c.id = lessons.course_id and c.status = 'published' and lessons.position = 1
  )
);

-- Explicit column grants prevent teachers from certifying their own attendance.
revoke update on public.workshop_regs from authenticated;
grant update (attended, attendance_status, attendance_verified_at, attendance_verified_by)
  on public.workshop_regs to authenticated;

revoke all on public.career_profiles, public.job_applications,
  public.notification_preferences from anon, authenticated;
grant select, insert, update, delete on public.career_profiles to authenticated;
grant select, insert on public.job_applications to authenticated;
grant select, insert, update, delete on public.notification_preferences to authenticated;
grant usage, select on sequence public.job_applications_id_seq to authenticated;

comment on column public.courses.status is
  'TeachersInn lifecycle: draft is unpublished, published is discoverable, archived preserves history.';
comment on column public.workshop_regs.attendance_verified_by is
  'Active administrator who made the attendance decision.';
