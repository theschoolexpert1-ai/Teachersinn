update public.courses c
set status = case when c.published then 'published' else 'draft' end,
    description = c.summary,
    estimated_minutes = coalesce((
      select sum(l.minutes) from public.lessons l where l.course_id = c.id
    ), 0),
    updated_at = c.created_at;

