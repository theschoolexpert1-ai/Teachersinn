-- TeachersInn Stage 2 schema synchronization.
-- Forward-only and additive: no application rows, Auth users, or Storage
-- objects are deleted or rewritten beyond deterministic backfills.

create table public.career_profiles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  professional_summary text not null default '',
  previous_institutions text not null default '',
  responsibilities text not null default '',
  qualifications text not null default '',
  certifications text not null default '',
  training text not null default '',
  skills text not null default '',
  specializations text not null default '',
  cv_template text not null default 'classic' check (cv_template in ('classic','modern')),
  updated_at timestamptz not null default now()
);

create table public.job_applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  job_id bigint not null references public.jobs(id) on delete cascade,
  status text not null default 'applied' check (status = 'applied'),
  applied_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, job_id)
);

create table public.notification_preferences (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  messages boolean not null default true,
  connections boolean not null default true,
  community boolean not null default true,
  workshops boolean not null default true,
  learning boolean not null default true,
  mentorship boolean not null default true,
  support boolean not null default true,
  updated_at timestamptz not null default now()
);

create index job_applications_user_applied_idx
  on public.job_applications (user_id, applied_at desc, id desc);
create index job_applications_job_user_idx
  on public.job_applications (job_id, user_id);

create trigger career_profiles_updated before update on public.career_profiles
for each row execute function public.set_updated_at();
create trigger job_applications_updated before update on public.job_applications
for each row execute function public.set_updated_at();
create trigger notification_preferences_updated before update on public.notification_preferences
for each row execute function public.set_updated_at();

