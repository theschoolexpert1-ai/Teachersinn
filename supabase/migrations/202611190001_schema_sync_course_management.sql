  references public.profiles(id) on delete set null;

create index workshop_regs_workshop_status_user_idx
  on public.workshop_regs (workshop_id, attendance_status, user_id);
create index workshop_regs_verified_by_idx
  on public.workshop_regs (attendance_verified_by)
  where attendance_verified_by is not null;

