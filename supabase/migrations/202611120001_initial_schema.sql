create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'name', ''))
  on conflict (id) do nothing;

  insert into public.account_settings (id, consent_at, consent_version)
  -- Consent is recorded only by the trusted server after it validates the
  -- accepted notice. Client-controlled Auth metadata is not authoritative.
  values (new.id, null, '1.0')
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

